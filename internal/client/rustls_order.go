// rustls ClientHello extension ordering — a faithful port of rustls 0.23.45.
//
// The genuine codex CLI (linux-x64 musl) uses rustls. Unlike Chrome — and
// unlike the previous codex dressing here, uTLS's ShuffleChromeTLSExtensions
// Fisher-Yates shuffle — rustls does NOT draw an arbitrary permutation. It emits
// its ClientHello extensions in an order derived from one random u16 "order
// seed":
//
//	rustls-0.23.45/src/msgs/handshake.rs:1076-1095
//	  fn order_insensitive_extensions_in_random_order(&self):
//	      let mut order = self.collect_used();
//	      order.retain(|ext| !(matches!(ext,
//	          ExtensionType::PreSharedKey
//	          | ExtensionType::EncryptedClientHello
//	          | ExtensionType::EncryptedClientHelloOuterExtensions)
//	          || self.contiguous_extensions.contains(ext)));
//	      order.sort_by_cached_key(|e| {
//	          let seed = ((self.order_seed as u32) << 16) | (u16::from(*e) as u32);
//	          low_quality_integer_hash(seed)
//	      });
//
//	src/msgs/handshake.rs:3199-3213   low_quality_integer_hash (u32, wrapping)
//	src/msgs/macros.rs:233-241        collect_used = struct-declaration order
//	src/client/hs.rs:122-128          order_seed = random_u16(secure_random)
//	src/rand.rs:26-30                 random_u16 = u16::from_be_bytes(2 bytes)
//	src/msgs/enums.rs:101-165         ExtensionType numeric ids
//
// Rust's slice::sort_by_cached_key is STABLE, so equal hash keys keep the
// collect_used declaration order; this port therefore sorts from that
// declaration order too (rustlsCodexExtDeclarationOrder). SNI and
// PSKKeyExchangeModes participate in the sort like any other extension. The
// rustls ECH/PSK fixed tail is vacuous for the codex ClientHello: it never
// carries PSK/ECH, and any extension type outside the codex set is rejected with
// an error rather than silently defaulted.
//
// License/provenance: ported from rustls 0.23.45
// (https://github.com/rustls/rustls), SPDX "Apache-2.0 OR ISC OR MIT"
// (rustls-0.23.45/Cargo.toml:34). The local crate snapshot under
// _artifacts/rs-source-0163/rustls-0.23.45/ ships no LICENSE files, so the
// verbatim upstream license/copyright text is intentionally NOT reproduced here:
// it must be attached from the released crate before any public distribution
// (pending — not fabricated), per the repo third-party NOTICE policy (see
// internal/modelverify/NOTICE.md for the precedent).

// rustlsCodexExtDeclarationOrder is the rustls ClientExtensions struct field
// order for the extensions the codex ClientHello carries — i.e. the order
// rustls's macro-generated collect_used() returns them in
// (rustls-0.23.45/src/msgs/handshake.rs:868-974; collect_used is generated by
// the extension_struct! macro in src/msgs/macros.rs:233-241). It is the
// stable-sort tie-break order.
var rustlsCodexExtDeclarationOrder = []uint16{
	0x0000, // ServerName (SNI)
	0x0005, // StatusRequest
	0x000a, // EllipticCurves (supported_groups)
	0x000b, // ECPointFormats
	0x000d, // SignatureAlgorithms
	0x0010, // ALProtocolNegotiation (ALPN)
	0x0017, // ExtendedMasterSecret
	0x0023, // SessionTicket
	0x002b, // SupportedVersions
	0x002d, // PSKKeyExchangeModes
	0x0033, // KeyShare
}

// rustlsLowQualityIntegerHash is a direct port of rustls's
// low_quality_integer_hash (rustls-0.23.45/src/msgs/handshake.rs:3199-3213).
// uint32 arithmetic wraps naturally, matching Rust's u32 wrapping_add and
// shifts; each statement's references to x are evaluated before the assignment,
// exactly as in the Rust original.
func rustlsLowQualityIntegerHash(x uint32) uint32 {
	x = x + 0x7ed55d16 + (x << 12)
	x = (x ^ 0xc761c23c) ^ (x >> 19)
	x = x + 0x165667b1 + (x << 5)
	x = (x + 0xd3a2646c) ^ (x << 9)
	x = x + 0xfd7046c5 + (x << 3)
	x = (x ^ 0xb55a4f09) ^ (x >> 16)
	return x
}

// rustlsExtTypeID maps a uTLS extension to the rustls ExtensionType id used as
// its sort key (rustls-0.23.45/src/msgs/enums.rs:101-165). Only the concrete
// types codexRustlsClientHelloSpec carries are recognised — an explicit type
// switch, no reflection or serialization — and anything else is an error so an
// unmapped extension can never be silently defaulted into the fingerprint.
func rustlsExtTypeID(ext utls.TLSExtension) (uint16, error) {
	switch ext.(type) {
	case *utls.SNIExtension:
		return 0x0000, nil
	case *utls.StatusRequestExtension:
		return 0x0005, nil
	case *utls.SupportedCurvesExtension:
		return 0x000a, nil
	case *utls.SupportedPointsExtension:
		return 0x000b, nil
	case *utls.SignatureAlgorithmsExtension:
		return 0x000d, nil
	case *utls.ALPNExtension:
		return 0x0010, nil
	case *utls.ExtendedMasterSecretExtension:
		return 0x0017, nil
	case *utls.SessionTicketExtension:
		return 0x0023, nil
	case *utls.SupportedVersionsExtension:
		return 0x002b, nil
	case *utls.PSKKeyExchangeModesExtension:
		return 0x002d, nil
	case *utls.KeyShareExtension:
		return 0x0033, nil
	default:
		return 0, fmt.Errorf("rustls order: unmapped ClientHello extension type %T", ext)
	}
}

// rustlsSortKey is rustls's sort key for one extension under a given order
// seed: low_quality_integer_hash(((seed as u32) << 16) | ext_id)
// (rustls-0.23.45/src/msgs/handshake.rs:1089-1092).
func rustlsSortKey(seed, extID uint16) uint32 {
	return rustlsLowQualityIntegerHash(uint32(seed)<<16 | uint32(extID))
}

// rustlsOrderEntry pairs an extension id with its precomputed sort key.
type rustlsOrderEntry struct {
	id  uint16
	key uint32
}

// rustlsOrderExtensions returns exts reordered exactly as rustls 0.23.45 orders
// its ClientHello extensions for the given per-connection order seed. The input
// set must be exactly the extensions codexRustlsClientHelloSpec carries; an
// unmapped or duplicate extension is an error. The returned slice is new — the
// caller's slice and the spec base are never mutated.
func rustlsOrderExtensions(exts []utls.TLSExtension, seed uint16) ([]utls.TLSExtension, error) {
	byID := make(map[uint16]utls.TLSExtension, len(exts))
	for _, ext := range exts {
		id, err := rustlsExtTypeID(ext)
		if err != nil {
			return nil, err
		}
		if _, dup := byID[id]; dup {
			return nil, fmt.Errorf("rustls order: duplicate ClientHello extension id 0x%04x", id)
		}
		byID[id] = ext
	}
	// Rebuild in rustls collect_used (declaration) order so a stable sort's
	// equal-key tie-breaks match rustls, then stable-sort by the seed-mixed hash.
	entries := make([]rustlsOrderEntry, 0, len(byID))
	for _, id := range rustlsCodexExtDeclarationOrder {
		if _, ok := byID[id]; ok {
			entries = append(entries, rustlsOrderEntry{id: id, key: rustlsSortKey(seed, id)})
		}
	}
	if len(entries) != len(byID) {
		return nil, errors.New("rustls order: extension id outside the codex ClientHello declaration set")
	}
	sort.SliceStable(entries, func(i, j int) bool { return entries[i].key < entries[j].key })
	out := make([]utls.TLSExtension, len(entries))
	for i, e := range entries {
		out[i] = byID[e.id]
	}
	return out, nil
}

// readRustlsOrderSeed reads the per-connection order seed the way rustls draws
// it: exactly 2 bytes from the secure RNG, big-endian
// (rustls-0.23.45/src/rand.rs:26-30 random_u16 = u16::from_be_bytes). A short
// read is an error — the seed is never defaulted.
func readRustlsOrderSeed(r io.Reader) (uint16, error) {
	var b [2]byte
	if _, err := io.ReadFull(r, b[:]); err != nil {
		return 0, err
	}
	return binary.BigEndian.Uint16(b[:]), nil
}

// codexRustlsOrderedExtensions draws a fresh per-connection order seed from
// crypto/rand (production) and returns the codex ClientHello extensions in the
// rustls order for that seed. dialUTLS calls it on the per-dial spec clone for
// the codex face only. Tests inject a failing reader via readRustlsOrderSeed
// directly (no global test hook).
func codexRustlsOrderedExtensions(exts []utls.TLSExtension) ([]utls.TLSExtension, error) {
	seed, err := readRustlsOrderSeed(rand.Reader)
	if err != nil {
		return nil, err
	}
	return rustlsOrderExtensions(exts, seed)
}
